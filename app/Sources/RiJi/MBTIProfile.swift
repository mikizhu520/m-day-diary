    private static let byType: [String: MBTIProfile] = Dictionary(uniqueKeysWithValues: all.map { ($0.type, $0) })

    static func find(_ type: String) -> MBTIProfile? {
        byType[UserProfile.normalizeMBTI(type)]
    }

    /// 设置页选完类型后显示的一行
    static func line(for type: String) -> String? {
        find(type)?.summary
    }

    /// 给系统提示词的一段。使用者没选类型时返回 nil。
    static func prompt(for type: String) -> String? {
        find(type)?.forPrompt
    }
