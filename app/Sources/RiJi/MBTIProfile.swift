// 从 epub 里逐章读出来后压缩成的这份数据 —— 每型四块：
//
//   title   书里给的称呼（「知识部长」）
//   alias   市面上常见的译名（「提倡者」）
//   traits  这个人是怎样的：感知/判断方式、最明显的长处
//   blind   容易踩的坑（书里「问题与发展机遇」那一节）
//   needs   书末「个人使用说明」浓缩成的一句话：跟这个人相处该注意什么
//
// 用途有两个：
//   1. 设置页选完 MBTI 后显示一行简介，让人确认选的是不是自己
//   2. 小迹的系统提示词 —— 知道对方是 INFJ，就知道他需要「先想清楚再说」，
//      别逼着立刻表态；知道是 ESTP，就知道他要的是行动方案不是长篇分析
//
// ⚠️ 类型只是理解一个人的参考角度，不是标签。注入提示词时会明确交代这一点。

struct MBTIProfile {
    var type: String
    var title: String
    var alias: String
    var traits: String
    var blind: String
    var needs: String

    /// 设置页那一行简介
    var summary: String { "\(title)（\(alias)）：\(traits)" }

    /// 给 AI 的一段话。只给「怎么跟这个人说话」，不给刻板印象式的评价。
    var forPrompt: String {
        """
        · \(type)（\(title)）：\(traits)
        · 容易卡住的地方：\(blind)
        · 跟他/她打交道：\(needs)
        """
    }
}

